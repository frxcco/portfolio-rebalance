package com.trading.portfolio.service;

import com.trading.portfolio.model.Allocation;
import com.trading.portfolio.model.PortfolioPosition;
import com.trading.portfolio.model.RebalancePlan;

import java.math.BigDecimal;
import java.util.Map;

/**
 * Service interface defining the contract for financial portfolio rebalancing engines.
 * <p>
 * Portfolio rebalancing is the algorithmic process of realigning the weightings of a portfolio's
 * asset holdings to match target asset allocation percentages. The engine calculates the precise
 * monetary and share deltas required to transition from the current state to the target state.
 * </p>
 * <p>
 * <b>Self-Financing Execution Priority Contract (Autofinanciamiento):</b><br>
 * Rebalance plans generated by implementations of this interface must prioritize liquidity by placing
 * all {@link com.trading.portfolio.model.OrderAction#SELL} orders before any
 * {@link com.trading.portfolio.model.OrderAction#BUY} orders. This guarantees that capital liberated
 * from overweight or liquidated positions is made available to finance subsequent asset purchases,
 * satisfying real-world brokerage and capital sufficiency constraints.
 * </p>
 */
public interface RebalanceEngine {

    /**
     * Calculates the execution plan required to rebalance a portfolio from its current positions
     * to the desired target allocations based on the total portfolio valuation.
     * <p>
     * Implementation Contract:
     * <ul>
     *   <li>Computes fractional share orders for each asset across current holdings and target allocations.</li>
     *   <li>Handles full liquidation for discontinued assets (target allocation of 0% or removed from targets).</li>
     *   <li>Orders trades in accordance with the self-financing principle: all SELL orders precede BUY orders.</li>
     *   <li>Applies a monetary threshold tolerance to avoid generating insignificant rounding dust orders.</li>
     * </ul>
     * </p>
     *
     * @param currentPositions map of current portfolio positions keyed by ticker symbol, must not be null
     * @param targetAllocations map of target allocations keyed by ticker symbol, must not be null
     * @param totalPortfolioValue total valuation of the portfolio before rebalancing, must not be null and non-negative
     * @return an immutable {@link RebalancePlan} containing ordered trades and portfolio valuation
     * @throws NullPointerException if {@code currentPositions}, {@code targetAllocations}, or {@code totalPortfolioValue} is null
     * @throws IllegalStateException if any stock in current positions or target allocations lacks an established valid price (&gt; 0)
     * @throws IllegalArgumentException if {@code totalPortfolioValue} is negative (&lt; 0)
     */
    RebalancePlan calculateRebalance(
            Map<String, PortfolioPosition> currentPositions,
            Map<String, Allocation> targetAllocations,
            BigDecimal totalPortfolioValue
    );
}
